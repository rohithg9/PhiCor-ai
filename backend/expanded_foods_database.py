async def seed_expanded_foods():
    """Seed expanded foods into the database"""
    client = AsyncIOMotorClient(MONGO_URL)
    db = client[DB_NAME]
    foods_collection = db.foods
    
    print("=" * 60)
    print("PhiCor Food Engine - Expanded Foods Database")
    print("=" * 60)
    
    inserted = 0
    updated = 0
    
    for food in EXPANDED_FOODS:
        food["created_at"] = datetime.utcnow()
        food["updated_at"] = datetime.utcnow()
        food["source"] = "PhiCor Comprehensive Database v1.0"
        
        result = await foods_collection.update_one(
            {"id": food["id"]},
            {"$set": food},
            upsert=True
        )
        
        if result.upserted_id:
            inserted += 1
            print(f"  ✓ {food['name']}")
        else:
            updated += 1
    
    print(f"\n✓ Foods: {inserted} inserted, {updated} updated")
    
    # Show totals by category
    categories = await foods_collection.aggregate([
        {"$group": {"_id": "$category", "count": {"$sum": 1}}},
        {"$sort": {"count": -1}}
    ]).to_list(100)
    
    print("\nFoods by category:")
    for cat in categories:
        print(f"  {cat['_id']}: {cat['count']}")
    
    total = await foods_collection.count_documents({})
    print(f"\n✓ Total foods in database: {total}")
    
    client.close()


if __name__ == "__main__":
    asyncio.run(seed_expanded_foods())
