class DatabaseExpander:
    def __init__(self, llm_key: str, mongo_url: str = "mongodb://localhost:27017"):
        self.llm_key = llm_key
        self.client = AsyncIOMotorClient(mongo_url)
        self.db = self.client['test_database']
    
    async def add_diseases(self, category: str, diseases: List[tuple]) -> Dict:
        """Add new diseases to the database"""
        added = 0
        skipped = 0
        
        for icd_code, name in diseases:
            # Check if disease already exists
            existing = await self.db.diseases.find_one({
                '$or': [
                    {'icd10_code': icd_code},
                    {'name': name}
                ]
            })
            
            if existing:
                skipped += 1
                continue
            
            # Create new disease document
            disease_id = str(uuid.uuid4())
            disease_doc = {
                'id': disease_id,
                'name': name,
                'icd10_code': icd_code,
                'category': category,
                'description': f'{name} - an {category} condition',
                'ai_enhanced': False,
                'fully_enhanced': False,
                'created_at': datetime.now(timezone.utc).isoformat(),
                'parameter_modifications': {},
                'symptoms': [],
                'clinical_signs': [],
                'diagnostic_tests': [],
                'treatments': [],
                'mathematical_models': []
            }
            
            await self.db.diseases.insert_one(disease_doc)
            added += 1
            logger.info(f"Added disease: {name} ({icd_code})")
        
        return {'added': added, 'skipped': skipped}
    
    async def add_all_new_diseases(self) -> Dict:
        """Add all new diseases from all categories"""
        total_added = 0
        total_skipped = 0
        
        for category, diseases in NEW_DISEASES_BY_CATEGORY.items():
            logger.info(f"Processing category: {category} ({len(diseases)} diseases)")
            result = await self.add_diseases(category, diseases)
            total_added += result['added']
            total_skipped += result['skipped']
            logger.info(f"  Added: {result['added']}, Skipped: {result['skipped']}")
        
        return {'total_added': total_added, 'total_skipped': total_skipped}
    
    async def add_drug(self, drug: Dict) -> bool:
        """Add a single drug to the database"""
        # Check if drug exists
        existing = await self.db.drugs.find_one({'name': drug['name']})
        if existing:
            return False
        
        drug_doc = {
            'id': str(uuid.uuid4()),
            'name': drug['name'],
            'drug_class': drug['class'],
            'category': drug['category'],
            'indications': drug['indications'],
            'created_at': datetime.now(timezone.utc).isoformat(),
            'enhanced': False
        }
        
        await self.db.drugs.insert_one(drug_doc)
        return True
    
    async def add_all_drugs(self) -> Dict:
        """Add all new drugs"""
        added = 0
        skipped = 0
        
        for drug in NEW_DRUGS:
            if await self.add_drug(drug):
                added += 1
                logger.info(f"Added drug: {drug['name']}")
            else:
                skipped += 1
        
        return {'added': added, 'skipped': skipped}
    
    async def enhance_drug(self, drug: Dict) -> bool:
        """Enhance a drug with AI-generated data"""
        if not LLM_AVAILABLE:
            return False
        
        try:
            session_id = str(uuid.uuid4())
            llm = LlmChat(
                api_key=self.llm_key,
                session_id=session_id,
                system_message="You are a pharmacology expert. Return only valid JSON."
            )
            
            prompt = DRUG_ENHANCEMENT_PROMPT.format(
                drug_name=drug['name'],
                drug_class=drug.get('drug_class', 'Unknown')
            )
            
            response = await llm.send_message(UserMessage(text=prompt))
            
            if hasattr(response, 'text'):
                text = response.text.strip()
            elif isinstance(response, str):
                text = response.strip()
            else:
                text = str(response).strip()
            
            # Clean markdown
            import re
            if text.startswith('```'):
                text = re.sub(r'^```\w*\n?', '', text)
                text = re.sub(r'\n?```$', '', text)
            
            data = json.loads(text)
            
            # Update drug document
            await self.db.drugs.update_one(
                {'id': drug['id']},
                {'$set': {
                    **data,
                    'enhanced': True,
                    'enhancement_date': datetime.now(timezone.utc).isoformat()
                }}
            )
            
            logger.info(f"Enhanced drug: {drug['name']}")
            return True
            
        except Exception as e:
            logger.error(f"Error enhancing drug {drug['name']}: {e}")
            return False
    
    async def run_expansion(self) -> Dict:
        """Run full database expansion"""
        logger.info("=" * 60)
        logger.info("STARTING DATABASE EXPANSION")
        logger.info("=" * 60)
        
        # Add diseases
        logger.info("\n--- Adding New Diseases ---")
        disease_result = await self.add_all_new_diseases()
        
        # Add drugs
        logger.info("\n--- Adding New Drugs ---")
        drug_result = await self.add_all_drugs()
        
        # Get final counts
        total_diseases = await self.db.diseases.count_documents({})
        total_drugs = await self.db.drugs.count_documents({})
        
        logger.info("\n" + "=" * 60)
        logger.info("EXPANSION COMPLETE")
        logger.info("=" * 60)
        logger.info(f"Diseases: Added {disease_result['total_added']}, Skipped {disease_result['total_skipped']}")
        logger.info(f"Drugs: Added {drug_result['added']}, Skipped {drug_result['skipped']}")
        logger.info(f"Total diseases: {total_diseases}")
        logger.info(f"Total drugs: {total_drugs}")
        
        return {
            'diseases': disease_result,
            'drugs': drug_result,
            'totals': {
                'diseases': total_diseases,
                'drugs': total_drugs
            }
        }


async def main():
    llm_key = os.environ.get('EMERGENT_LLM_KEY')
    
    if not llm_key:
        logger.error("EMERGENT_LLM_KEY not set!")
        return
    
    expander = DatabaseExpander(llm_key=llm_key)
    await expander.run_expansion()


if __name__ == "__main__":
    asyncio.run(main())
